"""Write README.md and .github/workflows/cards.yml from one card list.

Cards are rendered by a scheduled workflow into the cards-output branch, so
their numbers don't depend on the public instance's multi-day cache.
Rows are single-line with percentage spacers so the grid never wraps.

usage: python scripts/gen_readme.py [repo_root]
"""
import pathlib
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
RAW = "https://raw.githubusercontent.com/pipe1os/pipe1os/{branch}/{name}"
COLORS = {
    "dark": "bg_color=0c0c0d&title_color=ecebe6&text_color=8f8e89&icon_color=8f8e89&border_color=2c2c2d",
    "light": "bg_color=ffffff&title_color=0c0c0d&text_color=63625e&icon_color=63625e&border_color=d6d5cf",
}
DARK = '(prefers-color-scheme: dark)'
GAP = '<img src="assets/gap.svg" width="0.7%" alt="">'

CARDS = []  # (file stem, card type, options)


def pic(dark, light, alt, attrs='width="100%"'):
    return f'<picture><source media="{DARK}" srcset="{dark}"><img src="{light}" {attrs} alt="{alt}"></picture>'


def asset(name, alt, attrs='width="100%"'):
    return pic(f"assets/{name}-dark.svg", f"assets/{name}-light.svg", alt, attrs)


def card(kind, stem, options, alt, width):
    CARDS.append((stem, kind, options))
    url = lambda mode: RAW.format(branch="cards-output", name=f"{stem}-{mode}.svg")
    return pic(url("dark"), url("light"), alt, f'width="{width}"')


def pin(repo, owner=False):
    q = f"username=pipe1os&repo={repo}&description_lines_count=3&card_width=304&border_radius=8"
    if owner:
        q += "&show_owner=true"
    stem = "pin-" + repo.replace("/", "-").lower()
    return f'<a href="https://github.com/{repo}">{card("pin", stem, q, repo, "32.8%")}</a>'


def row(items):
    return "<p>" + GAP.join(items) + "</p>"


STREAK = lambda mode: RAW.format(branch="streak-output", name=f"streak-{mode}.svg")
LINKS = [("https://pipeos.dev", "portfolio", "pipeos.dev"),
         ("https://www.linkedin.com/in/pipeos/", "linkedin", "LinkedIn"),
         ("mailto:felipearce.2004@gmail.com", "email", "Email")]

stats_q = ("username=pipe1os&disable_animations=true&hide_title=true&show_icons=true&include_all_commits=true"
           "&hide=contribs&show=all_time_contribs,prs_merged&card_width=496&border_radius=8&ring_color=ff4f1f")
langs_q = "username=pipe1os&disable_animations=true&layout=compact&langs_count=8&card_width=338&border_radius=8"

blocks = [
    "<p>" + asset("header", "Felipe Arce, full stack developer in Concepción, Chile. Open to work.") + "</p>",
    "<p>\n" + "\n".join(f'  <a href="{url}">{asset(f"link-{key}", alt, "height=\"40\"")}</a>' for url, key, alt in LINKS) + "\n</p>",
    "<br>",
    "<p>" + asset("title-oss", "Contributed to") + "</p>",
    row([pin("withastro/astro", True), pin("trpc/trpc", True), pin("strands-agents/harness-sdk", True)]),
    row([pin("boykopovar/AnyPS5", True)]),
    "<br>",
    "<p>" + asset("title-work", "My work") + "</p>",
    row([pin("pipe1os/shipdot"), pin("pipe1os/modelinfo-cli"), pin("CEOUBB/CEOUBB")]),
    '<p><sub>I also run <a href="https://kumoweb.cl">Kumo</a>, a studio that builds websites and custom software for small businesses across Chile.</sub></p>',
    "<br>",
    "<p>" + asset("title-stack", "Stack") + "</p>",
    "<p>" + asset("stack", "Daily: TypeScript, React, Next.js, Astro, Python, C++. Learning: Svelte, Docker, AWS, Go, PostgreSQL.") + "</p>",
    "<br>",
    "<p>" + asset("title-activity", "Activity") + "</p>",
    row([card("stats", "stats", stats_q, "GitHub stats", "59%"), card("top-langs", "top-langs", langs_q, "Most used languages", "40.1%")]),
    "<p>" + pic(STREAK("dark"), STREAK("light"), "Contribution streak") + "</p>",
]
(ROOT / "README.md").write_text("\n\n".join(blocks) + "\n", encoding="utf-8")

steps = "".join(
    f"""
      - name: {stem} ({mode})
        uses: stats-organization/github-readme-stats-action@v2
        with:
          card: {kind}
          options: {options}&{COLORS[mode]}
          path: dist/{stem}-{mode}.svg
          token: ${{{{ secrets.STATS_TOKEN || secrets.GITHUB_TOKEN }}}}
          fail_on_error: true
"""
    for stem, kind, options in CARDS
    for mode in ("dark", "light")
)

workflow = f"""# Generated by scripts/gen_readme.py. Renders every README card into the cards-output branch.
name: Generate README cards

on:
  schedule: # execute every 12 hours
    - cron: "0 */12 * * *"

  workflow_dispatch:

  push:
    branches:
    - main

jobs:
  generate:
    permissions:
      contents: write
    runs-on: ubuntu-latest
    timeout-minutes: 10

    steps:{steps}
      - name: push cards to the output branch
        uses: crazy-max/ghaction-github-pages@v3.1.0
        with:
          target_branch: cards-output
          build_dir: dist
        env:
          GITHUB_TOKEN: ${{{{ secrets.GITHUB_TOKEN }}}}
"""
(ROOT / ".github/workflows/cards.yml").write_text(workflow, encoding="utf-8")
print(f"{len(CARDS) * 2} cards")
